-- =========================================
-- 2. 보험 가입 내역
--
-- 세 업체 모두 음식점업이라 대상 보험이 8개로 같다.
--   사회보험 4 (국민연금·건강보험·고용보험·산재보험)
--   의무보험 4 (개인정보보호·다중이용업소 화재배상·재난배상·가스사고배상)
-- 이 8개 안에서만 골라야 한다. 목록 밖 보험을 넣으면
-- 체크리스트 대상이 아니라 그냥 무시된다.
--
-- 업체마다 가입 정도를 다르게 두어 체크리스트가 갈리도록 했다.
-- =========================================

DELETE FROM mydata_insurance;

INSERT INTO mydata_insurance (mydata_id, insurance_id)
SELECT m.id, i.id
FROM (VALUES
          -- 맛있는 한상: 개인정보보호만 미가입 (8개 중 7개)
          ('1234567890', '국민연금'),
          ('1234567890', '건강보험'),
          ('1234567890', '고용보험'),
          ('1234567890', '산재보험'),
          ('1234567890', '다중이용업소 화재배상책임보험'),
          ('1234567890', '재난배상책임보험'),
          ('1234567890', '가스사고배상책임보험'),

          -- 서울분식: 사회보험 일부만. 의무보험 전부 미가입 (8개 중 2개)
          ('2345678901', '국민연금'),
          ('2345678901', '건강보험'),

          -- 카페 하루: 사회보험 전부 + 화재배상만 (8개 중 5개)
          ('3456789012', '국민연금'),
          ('3456789012', '건강보험'),
          ('3456789012', '고용보험'),
          ('3456789012', '산재보험'),
          ('3456789012', '다중이용업소 화재배상책임보험')
     ) AS v(brn, insurance_name)
         JOIN mydata m ON m.brn = v.brn
         JOIN insurance i ON i.name = v.insurance_name;