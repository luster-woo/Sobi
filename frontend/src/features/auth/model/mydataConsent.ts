export interface TransferItem {
  id: string
  label: string
  /** 어느 범위까지 가져오는지. 오른쪽에 회색으로 붙는다 */
  scope: string
  /**
   * 전부 필수다. 여섯 항목이 다 있어야 자격 판정·자금 조합·의무보험 진단이 돌아가고,
   * 하나라도 빠지면 제공할 수 있는 기능이 없다.
   *
   * 그래도 항목을 하나씩 보여주고 체크하게 두는 이유: 전송요구는 무엇을 보내는지
   * 항목 단위로 알린 뒤 받아야 한다(신용정보법 제33조의2). 목록만 나열하고 한 번에
   * 동의받으면 이용자가 뭘 넘기는지 확인할 기회가 없다.
   *
   * 나중에 일부를 선택으로 풀 수 있게 플래그로 남긴다.
   */
  required: boolean
}

